const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let selected='Nano Banana Pro',open=false;
const base={getClientRects:()=>[1],getAttribute:()=>null,getBoundingClientRect:()=>({left:100,right:300,top:140,bottom:180})};
const editor={getBoundingClientRect:()=>({left:50,right:400,top:100,bottom:130})};
const trigger={...base,get textContent(){return selected;}};
const options=['Nano Banana Pro','Nano Banana','Nano Banana Lite'].map(textContent=>({...base,textContent}));
const document={querySelectorAll:css=>css==='button,[role="button"]'?[trigger]:css.startsWith('[role="option"]')&&open?options:[]};
const context=vm.createContext({document,getComputedStyle:()=>({visibility:'visible'})});
vm.runInContext(fs.readFileSync(__dirname+'/flow-models.js','utf8'),context);
const models=context.FlowModels;
(async()=>{
 assert.equal(models.detect(editor).name,'Nano Banana Pro');
 selected='Nano Banana 2.1';
 assert.equal(models.detect(editor,['Nano Banana 2','Nano Banana 2.1']).name,'Nano Banana 2.1');
 selected='Nano Banana 2 Lite';
 assert.equal(models.detect(editor).name,'Nano Banana 2 Lite');
 selected='Nano Banana Pro';
 assert.equal(models.lower('Nano Banana Pro',['Nano Banana','Nano Banana Lite'],[],{}),'Nano Banana');
 assert.equal(models.lower('Nano Banana Pro',['Nano Banana','Nano Banana Lite'],[],{'Nano Banana':{disabled:true}}),'Nano Banana Lite');
 assert.equal(models.lower('Nano Banana Pro',['Imagen 4'],[],{}),null);
 const realOrder=['Nano Banana Pro','Nano Banana 2','Nano Banana 2 Lite'];
 assert.equal(models.lower('Nano Banana Pro',realOrder,realOrder,{'Nano Banana Pro':{disabled:true}}),'Nano Banana 2');
 assert.equal(models.lower('Nano Banana 2',realOrder,realOrder,{}),'Nano Banana 2 Lite');
 assert.equal(models.lower('Nano Banana Pro',realOrder,realOrder,{'Nano Banana 2':{disabled:true}}),'Nano Banana 2 Lite');
 assert.equal(await models.downgrade({editor:()=>editor,order:[],blocked:{},click:async e=>{if(e===trigger)open=true;else if(e!==editor)selected=e.textContent;else open=false;},sleep:async()=>{},check(){}}),'Nano Banana');
 assert.equal(open,false);
 console.log('PASS: detect active model; downgrade within family; skip disabled models; never infer cross-family ranking; verify switched label.');
})().catch(e=>{console.error(e);process.exitCode=1;});
